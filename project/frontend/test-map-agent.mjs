import assert from 'node:assert/strict'
import { loadTs } from './test-support.mjs'
const { validatePolygon, closePolygon } = loadTs('./src/lib/polygon.ts')
const { filterUnits, readMapAction, contextLabel, viewCoordinates } = loadTs('./src/lib/mapAgent.ts')
const { readWaterUnits, readInspectionReport } = loadTs('./src/lib/waterBudget.ts')
const { readAttachment } = loadTs('./src/lib/reportDownload.ts')
const ring = [[116.6, 39.7], [116.8, 39.7], [116.8, 39.9], [116.6, 39.9], [116.6, 39.7]]
assert.deepEqual(closePolygon(ring.slice(0, -1)), ring)
for (const invalid of [ring.slice(0, -1), [[0, 0], [1, 1], [2, 2], [0, 0]], [[0, 0], [2, 2], [0, 2], [2, 0], [0, 0]], [[0, 0], [NaN, 0], [0, 1], [0, 0]]]) assert.throws(() => validatePolygon(invalid))
assert.throws(() => closePolygon([]), /至少添加3个/)
const units = readWaterUnits([{ name: '超预算', lon: 116.72, lat: 39.8, water_used: 120, budget: 100 }, { name: '正常', lon: 116.73, lat: 39.81, water_used: 70, budget: 100 }])
assert.equal(filterUnits(units, 'normal')[0].name, '正常')
assert.equal(filterUnits(units, 'attention').length, 1)
const summary = { checked_count: 2, displayed_count: 1, over_budget: 1, normal: 1 }
const report = readInspectionReport({ ok: true, summary, data: [units[0]], all_units: units, area: { type: 'Polygon', coordinates: [ring] } })
assert.equal(report.all_units.length, 2)
assert.equal(filterUnits(report.all_units, 'normal').length, 1)
assert.deepEqual(report.area.coordinates[0], ring)
assert.equal(viewCoordinates([], { coordinates: ring }).length, 4)
assert.equal(viewCoordinates(units, { coordinates: ring }).length, 6)
assert.deepEqual(viewCoordinates(units, { coordinates: ring }, true), [[units[0].lon, units[0].lat]])
assert.equal(readMapAction({ ok: true, action: 'set_layer', layer: 'rivers', visibility: 'hide' }).visible, false)
assert.equal(readMapAction({ ok: true, action: 'set_layer', layer: 'streets', visibility: 'hide' }), null)
assert.equal(readMapAction({ ok: true, action: 'eval', code: 'danger' }), null)
assert.equal(readMapAction({ ok: false, action: 'reset_map' }), null)
assert.equal(readMapAction({ ok: true, action: 'locate_unit', data: [units[0]] }).unit.name, '超预算')
assert.match(contextLabel({ available: true, selected_unit: '企业', area: { coordinates: ring } }), /企业.*4 个顶点/)
assert.equal(readAttachment({ filename: '../evil/brief', markdown: '简报', csv: '清单' }).filename, '.._evil_brief')
assert.equal(readAttachment({ filename: '报告', markdown: 12, csv: '' }), null)
console.log('Passed: polygon closure/crossing/coordinates, scope-preserving filters, whitelisted map actions, selection context and report attachments.')
